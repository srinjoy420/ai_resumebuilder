                properties: {
                    question: {
                        type: "string",
                        description: "The behavioral interview question."
                    },
                    intension: {
                        type: "string",
                        description: "Explain what the interviewer is evaluating in 1-2 sentences."
                    },
                    answer: {
                        type: "string",
                        description: "Give a concise interview-ready answer in 3-5 sentences."
                    }
                },

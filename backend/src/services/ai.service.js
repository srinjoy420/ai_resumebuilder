async function generateIntervieweReport({ resume, selfDescription, jobDecsription }) {
    const prompt = `
Analyze the candidate against the job description.

JOB DESCRIPTION:
${jobDecsription}

RESUME:
${resume}

SELF DESCRIPTION:
${selfDescription}

Create a concise interview preparation report.

Requirements:
- Match score from 0-100.
- Exactly 3 technical interview questions.
- Exactly 2 behavioral interview questions.
- Identify the most important skill gaps.
- Create a practical 3-day preparation plan.
- Keep explanations concise.
- Keep interview answers to 3-5 sentences.
- Base the analysis only on the provided information.
`
    const res = await generateWithRetry(prompt, interviewReportSchema)
    const jsonContent = JSON.parse(res.text)
    console.log("✅ Interview report generated successfully")
    return jsonContent
}

async function generatePdfFormatHtml(htmlContent) {
    let browser
    try {
        const executablePath = process.env.NODE_ENV === "production" && process.env.PUPPETEER_EXECUTABLE_PATH
            ? process.env.PUPPETEER_EXECUTABLE_PATH
            : await puppeteer.executablePath()
        browser = await puppeteer.launch({
            headless: "new",
            args: ["--no-sandbox", "--disable-setuid-sandbox", "--disable-dev-shm-usage",  // ✅ add
                "--disable-gpu" ],
            executablePath
        })
        const page = await browser.newPage()
        await page.setContent(htmlContent, { waitUntil: "networkidle0" })
        console.time("PDF Generation")
        const pdfBuffer = await page.pdf({
            format: "A4",
            margin: {
                top: "20mm",
                bottom: "20mm",
                left: "15mm",
                right: "15mm"
            }
        })
        console.timeEnd("PDF Generation")
        return pdfBuffer
    } finally {
        if (browser) {
            await browser.close()
        }
    }
}

async function generateResumePdf({ resume, selfDescription, jobDecsription }) {
    const resumePdfSchema = {
        type: "object",
        description: "The generated resume as a single HTML document",
        properties: {
            html: {
                type: "string",
                description: "The HTML content of the resume which can be converted to PDF using puppeteer"
            }
        },
        required: ["html"]
    }

    const prompt = `
Generate resume for a candidate with the following details:
    Resume: ${resume}
    Self Description: ${selfDescription}
    Job Description: ${jobDecsription}

    the response should be a JSON object with a single field "html" which contains the HTML content of the resume which can be converted to PDF using any library like puppeteer.
    The resume should be tailored for the given job description and should highlight the candidate's strengths and relevant experience. The HTML content should be well-formatted and structured, making it easy to read and visually appealing.
    The content of resume should not sound like it is generated by AI and should be as close as possible to a real human-written resume.
    You can highlight the content using some colors or different font styles but the overall design should be simple and professional.
    The content should be ATS friendly, i.e. it should be easily parsable by ATS systems without losing important information.
    The resume should not be so lengthy, it should ideally be 1 page long when converted to PDF. Focus on quality rather than quantity.
    `

    const res = await generateWithRetry(prompt, resumePdfSchema)
    const jsonContent = JSON.parse(res.text)

    if (!jsonContent?.html || typeof jsonContent.html !== "string") {
        throw new Error("AI returned an invalid resume payload.")
    }

    console.log("✅ Resume HTML generated successfully")
    const pdfBuffer = await generatePdfFormatHtml(jsonContent.html)
    return pdfBuffer
}

